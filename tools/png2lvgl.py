"""Convert an 8-bit RGB/RGBA non-interlaced PNG into an LVGL 9 RGB565 image descriptor (C file).

Standard library only. Transparent pixels are composited over black, which is what a round display shows outside the glass.

    python tools/png2lvgl.py firmware/assets/splash.png firmware/components/marine_ui/splash_img.c marine_splash_img
    python tools/png2lvgl.py --probe image.png X0 Y0 X1 Y1     # print the RGB values of a pixel row/area (layout work)
"""
import struct
import sys
import zlib


def read_png(path):
    data = open(path, "rb").read()
    if data[:8] != b"\x89PNG\r\n\x1a\n":
        raise SystemExit("not a PNG")
    pos, idat, width, height, depth, ctype, interlace = 8, b"", 0, 0, 0, 0, 0
    while pos < len(data):
        n, typ = struct.unpack(">I4s", data[pos:pos + 8])
        body = data[pos + 8:pos + 8 + n]
        pos += 12 + n
        if typ == b"IHDR":
            width, height, depth, ctype, _, _, interlace = struct.unpack(">IIBBBBB", body)
        elif typ == b"IDAT":
            idat += body
    if depth != 8 or ctype not in (2, 6) or interlace:
        raise SystemExit("need 8-bit RGB or RGBA, not interlaced")
    bpp = 4 if ctype == 6 else 3
    raw = zlib.decompress(idat)
    stride = width * bpp
    rows, prev = [], bytearray(stride)
    for y in range(height):
        f = raw[y * (stride + 1)]
        cur = bytearray(raw[y * (stride + 1) + 1:(y + 1) * (stride + 1)])
        for i in range(stride):
            a = cur[i - bpp] if i >= bpp else 0
            b = prev[i]
            c = prev[i - bpp] if i >= bpp else 0
            if f == 1:
                cur[i] = (cur[i] + a) & 255
            elif f == 2:
                cur[i] = (cur[i] + b) & 255
            elif f == 3:
                cur[i] = (cur[i] + ((a + b) >> 1)) & 255
            elif f == 4:
                p = a + b - c
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                pr = a if pa <= pb and pa <= pc else (b if pb <= pc else c)
                cur[i] = (cur[i] + pr) & 255
        rows.append(cur)
        prev = cur
    px = []
    for row in rows:
        line = []
        for x in range(width):
            r, g, b = row[x * bpp], row[x * bpp + 1], row[x * bpp + 2]
            a = row[x * bpp + 3] if bpp == 4 else 255
            line.append((r * a // 255, g * a // 255, b * a // 255))
        px.append(line)
    return width, height, px


def main():
    if len(sys.argv) >= 7 and sys.argv[1] == "--probe":
        _, _, px = read_png(sys.argv[2])
        x0, y0, x1, y1 = map(int, sys.argv[3:7])
        for y in range(y0, y1 + 1):
            print(y, " ".join("%02x%02x%02x" % px[y][x] for x in range(x0, x1 + 1)))
        return
    src, dst, name = sys.argv[1:4]
    w, h, px = read_png(src)
    out = []
    for line in px:
        for r, g, b in line:
            v = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
            out.append(v & 255)  # LVGL RGB565 is little endian in memory
            out.append(v >> 8)
    with open(dst, "w", newline="\n") as f:
        f.write("/* Generated by tools/png2lvgl.py from %s. Do not edit. */\n" % src.replace("\\", "/").split("/")[-1])
        f.write('#include "lvgl.h"\n\n')
        f.write("static const uint8_t %s_map[] = {\n" % name)
        for i in range(0, len(out), 24):
            f.write("    " + ",".join("0x%02x" % b for b in out[i:i + 24]) + ",\n")
        f.write("};\n\n")
        f.write("const lv_image_dsc_t %s = {\n" % name)
        f.write("    .header = { .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_RGB565, .w = %d, .h = %d, .stride = %d },\n"
                % (w, h, w * 2))
        f.write("    .data_size = sizeof(%s_map),\n    .data = %s_map,\n};\n" % (name, name))
    print("wrote %s: %dx%d, %d bytes" % (dst, w, h, len(out)))


main()
